import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {spawnSync} from 'node:child_process';
import {createHash} from 'node:crypto';
import {prepareMediaPreview} from '../engine/scripts/preview-media.mjs';
import {readImageMetadata,readImageAnimation} from '../engine/scripts/image-metadata.mjs';
const executable=process.env.DREAM_TEST_FFMPEG;
assert.ok(executable,'Set DREAM_TEST_FFMPEG to the verified FFmpeg executable');
const here=path.dirname(fileURLToPath(import.meta.url));await fs.mkdir(path.join(here,'output'),{recursive:true});
const directory=await fs.mkdtemp(path.join(here,'output','preview-')),source=path.join(directory,'moving.webm'),state=path.join(directory,'state');
const generated=spawnSync(executable,['-nostdin','-hide_banner','-loglevel','error','-f','lavfi','-i','testsrc2=size=320x180:rate=12:duration=7','-c:v','libvpx-vp9','-threads','2','-deadline','realtime',source],{windowsHide:true});
assert.equal(generated.status,0,String(generated.stderr));
const digest=async file=>createHash('sha256').update(await fs.readFile(file)).digest('hex');
const original=await digest(source),options={ensureRuntime:async()=>executable};
const result=await prepareMediaPreview(source,state,options),bytes=await fs.readFile(result.path);
assert.equal(result.animated,true);assert.equal(result.cacheUsed,false);
const meta=readImageMetadata(bytes,'.gif'),animation=readImageAnimation(bytes,'.gif');
assert.ok(meta.width<=384&&meta.height<=216);assert.equal(animation.frameCount,72);assert.equal(bytes.at(-1),0x3b);
const cached=await prepareMediaPreview(source,state,{ensureRuntime:async()=>{throw new Error('must use cache');}});assert.equal(cached.cacheUsed,true);
await fs.writeFile(result.path,'broken');const repaired=await prepareMediaPreview(source,state,options);assert.equal(repaired.cacheUsed,false);
const fromGif=await prepareMediaPreview(repaired.path,state,options);assert.equal(fromGif.animated,true);
const image=path.join(directory,'static.jpg');await fs.writeFile(image,'static test');assert.equal((await prepareMediaPreview(image,state,options)).path,image);
await assert.rejects(prepareMediaPreview(path.join(directory,'missing.mp4'),state,options));
const bad=path.join(directory,'bad.mp4');await fs.writeFile(bad,'bad');await assert.rejects(prepareMediaPreview(bad,state,options));
assert.equal((await fs.readdir(path.join(state,'previews'))).some(name=>name.includes('.part.')),false);
assert.equal(await digest(source),original);
console.log(JSON.stringify({pass:true,cases:8,frames:animation.frameCount,previewSeconds:6,sourcePreserved:true}));
